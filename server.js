/* ---------- GET /health ---------- */
app.get("/health", async (req, res) => {
  try {
    await pool.query("SELECT 1");
    res.status(200).json({ status: "ok", database: "ok" });
  } catch (error) {
    console.error("Health check failed:", error.message);
    res.status(503).json({ status: "error", database: "unreachable", message: "Database check failed." });
  }
});

/* ---------- record routes ---------- */
app.use("/api/records", require("./routes/records"));

/* ---------- unknown routes -> 404 JSON ---------- */
app.use((req, res) => {
  res.status(404).json({ message: "Route not found." });
});

/* ---------- error middleware (4 parameters) ---------- */
// eslint-disable-next-line no-unused-vars
app.use((error, req, res, next) => {
  if (error.type === "entity.parse.failed") {
    return res.status(400).json({ message: "Malformed JSON in request body." });
  }
  if (error.type === "entity.too.large") {
    return res.status(400).json({ message: "Request body is too large." });
  }
  console.error("Unexpected error:", error);
  res.status(500).json({ message: "Something went wrong on the server. Please try again." });
});

/* ---------- start ---------- */
const port = process.env.PORT || 3000;

initDb()
  .then(() => console.log("Database ready."))
  .catch((error) => console.error("Database setup failed (check DATABASE_URL):", error.message))
  .finally(() => {
    app.listen(port, "0.0.0.0", () => {
      console.log(`Server listening on port ${port}`);
    });
  });
